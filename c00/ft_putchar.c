#include <unistd.h>

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

int	main(void)
{
	ft_putchar('j');
	ft_putchar('i');
	ft_putchar('n');
	ft_putchar('x');
	ft_putchar('\n');
	return (0);
}
